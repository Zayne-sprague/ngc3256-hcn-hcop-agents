def pairs(ia,ib):
    r=lambda i:(np.exp(lnI['H3'][i]-lnI['H1'][i]),np.exp(lnI['O3'][i]-lnI['O1'][i]))
    h=np.exp(lnI['H1'][ib][None,:]-lnI['H1'][ia][:,None]) # unused
    rhN,roN=r(ia); rhS,roS=r(ib)
    snH=rhS[None,:]/rhN[:,None]; snO=roS[None,:]/roN[:,None]
    c10=(np.exp(lnI['H1'][ia]-lnI['O1'][ia])[:,None])/(np.exp(lnI['H1'][ib]-lnI['O1'][ib])[None,:])
    return snH,snO,c10
def summarize(name,recs):
    if not recs: P(f'{name}: no pair'); return
    a=np.concatenate(recs); c=a[:,0]; chi=a[:,1]
    sel=chi<4.0
    P(f'{name}: pairs consistent with S/N values (chi2<4): {sel.sum()} of {len(a)}; predicted 1-0 contrast N/S: median {np.median(c[sel]):.2f}, 5-95% [{np.percentile(c[sel],5):.2f},{np.percentile(c[sel],95):.2f}], max {c[sel].max():.2f}; '
      f'fraction reaching >=1.35: {(c[sel]>=1.35).mean():.3f}') if sel.sum() else P(f'{name}: none consistent')
# H_exc: same (NO,A); H_col: same A, any NO; H_abund: same T,n,NO, A differs
rec_exc=[]; rec_col=[]
for k in np.unique(key):
    ii=idx[key==k]; snH,snO,c10=pairs(ii,ii); chi=((snH-sn_obs[0])/sn_err[0])**2+((snO-sn_obs[1])/sn_err[1])**2
    rec_exc.append(np.stack([c10.ravel(),chi.ravel()],1))
