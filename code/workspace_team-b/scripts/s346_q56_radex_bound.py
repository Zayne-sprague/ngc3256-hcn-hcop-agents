summarize('H_col (same A; Tk, n, N(HCO+) free per nucleus: excitation+opacity)',rec_col)
# how much do the S/N values fix: |D| range generated by excitation-only pairs having c10 in 1.35-1.55
a=np.concatenate(rec_exc); sel=(a[:,0]>=1.35)&(a[:,0]<=1.55)
